#!/usr/bin/env bash
# Builds the Office add-in into $OFFICE_TARGET/ms-office/addin/ (docs/ms-addin/PLAN.md section 6):
#   UzTranslit.OfficeAddin.dll (AnyCPU, .NET Framework 4.x, no PIA), x86/ and x64/uz_translit_ffi.dll (static CRT),
#   brand-name.txt (the product name from brand/brand.toml, read by register.ps1).
# One version source: brand/brand.toml [product] version (and name, vendor, copyright) is stamped into all three DLLs
# (assembly attributes; a VERSIONINFO resource for the Rust DLLs) and read by build-msi.ps1 for the MSI.
# Needs: rustup targets i686-pc-windows-msvc and x86_64-pc-windows-msvc, MSVC (link.exe), the Windows SDK (rc.exe),
# Roslyn csc (VS Build Tools here, Visual Studio on the GitHub windows runner).
# Env: OFFICE_TARGET (required), CSC (csc.exe; default: found with vswhere), ADDIN_OFFLINE (cargo flag, default --offline).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
: "${OFFICE_TARGET:?set OFFICE_TARGET (build output root)}"
offline="${ADDIN_OFFLINE---offline}"
out="$OFFICE_TARGET/ms-office/addin"
gen="$OFFICE_TARGET/ms-office/gen"
mkdir -p "$out/x86" "$out/x64" "$gen"

# --- brand/brand.toml [product]: the one source of name, vendor, version, copyright
brand() { sed -n '/^\[product\]/,/^\[/{s/^'"$1"' = "\(.*\)"$/\1/p}' "$root/brand/brand.toml"; }
name="$(brand name)"; vendor="$(brand vendor)"; version="$(brand version)"; copyright="$(brand copyright)"
[ -n "$name" ] && [ -n "$vendor" ] && [ -n "$copyright" ] || { echo "brand/brand.toml [product] name/vendor/copyright missing" >&2; exit 1; }
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "brand/brand.toml [product] version must be X.Y.Z, got '$version'" >&2; exit 1; }
product="$name Office add-in"
v4="$version.0"; vc="${v4//./,}"
name_cyrl="$(brand name_uz_cyrl)"
printf '%s\n' "$name" > "$out/brand-name.txt"
printf '%s\n%s\n' "$name" "$name_cyrl" > "$gen/brand.txt"   # embedded: the ribbon tab label

# --- tools
win() { cygpath -w "$1"; }
if [ -z "${CSC:-}" ]; then
  CSC="$("${ProgramFiles:-C:/Program Files} (x86)/Microsoft Visual Studio/Installer/vswhere.exe" -latest -products '*' -find 'MSBuild\**\Bin\Roslyn\csc.exe' | head -1 | tr -d '\r')"
fi
[ -n "$CSC" ] || { echo "csc.exe not found (set CSC)" >&2; exit 1; }
rc="$(ls -d "/c/Program Files (x86)/Windows Kits/10/bin/"10.*/x64/rc.exe 2>/dev/null | sort -V | tail -1)"
[ -n "$rc" ] || { echo "rc.exe (Windows SDK) not found" >&2; exit 1; }

# --- VERSIONINFO for the Rust DLLs (architecture-neutral .res, given to the MSVC linker)
esc() { printf '%s' "$1" | sed 's/"/""/g'; }
cat > "$gen/ffi.rc" <<EOF
1 VERSIONINFO
FILEVERSION $vc
PRODUCTVERSION $vc
FILEOS 0x40004
FILETYPE 0x2
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "CompanyName", "$(esc "$vendor")"
      VALUE "FileDescription", "Uzbek transliteration engine (uz-translit)"
      VALUE "FileVersion", "$version"
      VALUE "InternalName", "uz_translit_ffi"
      VALUE "LegalCopyright", "$(esc "$copyright")"
      VALUE "OriginalFilename", "uz_translit_ffi.dll"
      VALUE "ProductName", "$(esc "$product")"
      VALUE "ProductVersion", "$version"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
EOF
"$rc" -nologo -c65001 -fo "$(win "$gen/ffi.res")" "$(win "$gen/ffi.rc")"   # "-" switches: Git Bash rewrites "/x" arguments as paths

# --- Rust engine, x86 and x64. Static CRT: no VC++ redistributable on the client. /DEPENDENTLOADFLAG as in
# .cargo/config.toml (review m8).
flags="-C target-feature=+crt-static -C link-arg=/DEPENDENTLOADFLAG:0xA00 -C link-arg=$(win "$gen/ffi.res")"
export CARGO_TARGET_I686_PC_WINDOWS_MSVC_RUSTFLAGS="$flags" CARGO_TARGET_X86_64_PC_WINDOWS_MSVC_RUSTFLAGS="$flags"
export CARGO_TARGET_DIR="$OFFICE_TARGET/ms-office/cargo"
for t in i686-pc-windows-msvc:x86 x86_64-pc-windows-msvc:x64; do
  cargo +stable-x86_64-pc-windows-msvc build $offline --release -p uz-translit-ffi --target "${t%%:*}" --manifest-path "$root/Cargo.toml"
  cp "$CARGO_TARGET_DIR/${t%%:*}/release/uz_translit_ffi.dll" "$out/${t##*:}/"
done

# --- C# host, with the same metadata as assembly attributes (csc writes them into its version resource)
cs() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
cat > "$gen/AssemblyInfo.cs" <<EOF
// Generated by integrations/ms-office/build.sh from brand/brand.toml. Do not edit.
using System.Reflection;
[assembly: AssemblyTitle("$(cs "$product")")]
[assembly: AssemblyDescription("Uzbek Latin/Cyrillic transliteration for Microsoft Office")]
[assembly: AssemblyCompany("$(cs "$vendor")")]
[assembly: AssemblyProduct("$(cs "$product")")]
[assembly: AssemblyCopyright("$(cs "$copyright")")]
[assembly: AssemblyVersion("$v4")]
[assembly: AssemblyFileVersion("$v4")]
[assembly: AssemblyInformationalVersion("$version")]
EOF
"$CSC" -nologo -target:library -platform:anycpu -optimize+ -warnaserror+ -utf8output \
  -out:"$(win "$out/UzTranslit.OfficeAddin.dll")" \
  -r:Microsoft.CSharp.dll -r:System.Core.dll -r:System.Xml.dll -r:System.Drawing.dll -r:System.Windows.Forms.dll \
  -resource:"$(win "$here/src/customUI.xml")",customUI.xml \
  -resource:"$(win "$root/i18n/msaddin.tsv")",msaddin.tsv \
  -resource:"$(win "$gen/brand.txt")",brand.txt \
  "$(win "$gen/AssemblyInfo.cs")" $(for f in "$here"/src/*.cs; do win "$f"; done)

# --- every binary carries the same product name and version
powershell -NoProfile -Command "
  \$bad = 0
  foreach (\$f in '$(win "$out/UzTranslit.OfficeAddin.dll")', '$(win "$out/x86/uz_translit_ffi.dll")', '$(win "$out/x64/uz_translit_ffi.dll")') {
    \$v = (Get-Item \$f).VersionInfo
    if (\$v.ProductName -ne '$(printf '%s' "$product" | sed "s/'/''/g")' -or \$v.ProductVersion -ne '$version' -or \$v.FileVersion -notlike '$version*') { Write-Output \"version metadata wrong: \$f ProductName='\$(\$v.ProductName)' ProductVersion='\$(\$v.ProductVersion)' FileVersion='\$(\$v.FileVersion)'\"; \$bad = 1 }
  }
  exit \$bad"
echo "built: $out ($product $version)"
ls -l "$out" "$out/x86" "$out/x64"
