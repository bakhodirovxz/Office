//! Build-script half of the brand overlay hook. Reads `$OFFICE_OVERLAY_DIR/overlay.env` (written by
//! `cargo xt overlay`) and writes `$OUT_DIR/office_overlay_gen.rs`, the constants behind `office_overlay.rs`.
//! With `OFFICE_OVERLAY_DIR` unset every constant holds upstream's own value, so such a build behaves like upstream.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Upstream's own values: the app's name token and its Wayland/X11 app id.
const UPSTREAM_NAME: &str = "GridCraft";
const UPSTREAM_APP_ID: &str = "ai.storyteller.gridcraft";

pub fn run() {
    println!("cargo::rerun-if-env-changed=OFFICE_OVERLAY_DIR");
    println!("cargo::rerun-if-changed=build_office.rs");
    println!("cargo::rustc-check-cfg=cfg(office_overlay)");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("office_overlay_gen.rs");
    let dir = std::env::var_os("OFFICE_OVERLAY_DIR").map(PathBuf::from).filter(|d| d.join("overlay.env").is_file());
    let text = match &dir {
        Some(d) => {
            println!("cargo::rustc-cfg=office_overlay");
            generate(d)
        }
        None => generate_upstream(),
    };
    if let Err(e) = std::fs::write(&out, text) {
        println!("cargo::error=writing {}: {e}", out.display());
    }
}

fn parse(dir: &Path) -> HashMap<String, String> {
    let file = dir.join("overlay.env");
    println!("cargo::rerun-if-changed={}", file.display());
    let text = std::fs::read_to_string(&file).unwrap_or_default();
    text.lines().filter_map(|l| l.split_once('=')).map(|(k, v)| (k.trim().to_string(), v.to_string())).collect()
}

/// An `include_bytes!` path: absolute, forward slashes, registered for rebuilds.
fn include_path(dir: &Path, name: &str) -> String {
    let p = dir.join(name);
    println!("cargo::rerun-if-changed={}", p.display());
    p.to_string_lossy().replace(std::path::MAIN_SEPARATOR, "/")
}

fn flag(env: &HashMap<String, String>, key: &str) -> bool {
    env.get(key).is_some_and(|v| v == "1")
}

fn pairs(env: &HashMap<String, String>, prefix: &str) -> String {
    let mut s = String::from("&[");
    for lang in ["en", "ru", "uz-latn", "uz-cyrl"] {
        if let Some(v) = env.get(&format!("{prefix}_{lang}")) {
            let _ = write!(s, "({lang:?}, {v:?}), ");
        }
    }
    s + "]"
}

fn generate(dir: &Path) -> String {
    let env = parse(dir);
    let get = |k: &str| env.get(k).cloned().unwrap_or_default();
    let mut o = String::from("// GENERATED by build_office.rs from $OFFICE_OVERLAY_DIR/overlay.env. Do not edit.\n");
    let _ = writeln!(o, "pub const ACTIVE: bool = true;");
    let _ = writeln!(o, "pub const PRODUCT_NAME: &str = {:?};", get("PRODUCT_NAME"));
    let _ = writeln!(o, "pub const APP_NAME: &str = {:?};", get("APP_NAME"));
    let _ = writeln!(o, "pub const APP_NAMES: &[(&str, &str)] = {};", pairs(&env, "APP_NAME"));
    let names: Vec<String> = get("UPSTREAM_NAMES").split(',').filter(|s| !s.is_empty()).map(str::to_string).collect();
    let _ = writeln!(o, "pub const UPSTREAM_NAMES: &[&str] = &{names:?};");
    let _ = writeln!(o, "pub const APP_ID: &str = {:?};", get("APP_ID"));
    let _ = writeln!(o, "pub const VERSION: &str = {:?};", get("VERSION"));
    let _ = writeln!(o, "pub const COPYRIGHT: &str = {:?};", get("COPYRIGHT"));
    let _ = writeln!(o, "pub const ATTRIBUTION: &[(&str, &str)] = {};", pairs(&env, "ATTRIBUTION"));
    for (name, key) in [
        ("COMMUNITY", "COMMUNITY"),
        ("SHARE", "SHARE"),
        ("ZOTERO", "ZOTERO"),
        ("UPDATE_CHECK", "UPDATE_CHECK"),
        ("UPSTREAM_LINKS", "UPSTREAM_LINKS"),
        ("CONTRIBUTORS_TAB", "CONTRIBUTORS_TAB"),
    ] {
        let _ = writeln!(o, "pub const {name}: bool = {};", flag(&env, key));
    }
    let _ = writeln!(o, "pub const LINK_WEBSITE: &str = {:?};", get("LINK_WEBSITE"));
    let icon = get("ICON_PNG");
    if icon.is_empty() {
        let _ = writeln!(o, "pub static ICON_PNG: Option<&[u8]> = None;");
    } else {
        let _ = writeln!(o, "pub static ICON_PNG: Option<&[u8]> = Some(include_bytes!({:?}));", include_path(dir, &icon));
    }
    let fonts: Vec<String> = get("FONTS").split(',').filter(|s| !s.is_empty()).map(str::to_string).collect();
    let mut list = String::new();
    for (i, f) in fonts.iter().enumerate() {
        let key = if i == 0 { "office-fallback-sans" } else { "office-fallback-mono" };
        let _ = write!(list, "({key:?}, include_bytes!({:?}) as &[u8]), ", include_path(dir, f));
    }
    let _ = writeln!(o, "pub static FALLBACK_FONTS: &[(&str, &[u8])] = &[{list}];");
    o + &uzbek(Some(dir)) + &russian(Some(dir))
}

/// The Uzbek catalogs that `cargo xt i18n export` wrote next to `overlay.env` (`key<TAB>translation` lines). Only when both
/// are there does the build get `cfg(office_uz)`, which adds uz-latn and uz-cyrl to `Language`. Each catalog becomes a
/// `match` function shaped like the ones in `src/i18n/*.rs`.
fn uzbek(dir: Option<&Path>) -> String {
    println!("cargo::rustc-check-cfg=cfg(office_uz)");
    let files = dir.map(|d| [d.join("catalog-uz-latn.tsv"), d.join("catalog-uz-cyrl.tsv")]).filter(|f| f.iter().all(|p| p.is_file()));
    let mut o = String::new();
    let Some(files) = files else {
        let _ = writeln!(o, "pub const EXTRA_LANGS: usize = 0;");
        let _ = writeln!(o, "pub const NAME_UZ_LATN: &str = \"\";\npub const NAME_UZ_CYRL: &str = \"\";");
        return o;
    };
    println!("cargo::rustc-cfg=office_uz");
    let meta = dir.map(|d| d.join("catalog-meta.env")).unwrap_or_default();
    println!("cargo::rerun-if-changed={}", meta.display());
    let meta: HashMap<String, String> = std::fs::read_to_string(&meta)
        .unwrap_or_default()
        .lines()
        .filter_map(|l| l.split_once('='))
        .map(|(k, v)| (k.to_string(), v.trim().to_string()))
        .collect();
    let _ = writeln!(o, "pub const EXTRA_LANGS: usize = 2;");
    for ((key, name), file) in [("LATN", "O\u{2bb}zbekcha"), ("CYRL", "Ўзбекча")].into_iter().zip(files) {
        println!("cargo::rerun-if-changed={}", file.display());
        let _ = writeln!(o, "pub const NAME_UZ_{key}: &str = {:?};", meta.get(&format!("NAME_UZ_{key}")).map_or(name, String::as_str));
        let _ = writeln!(o, "pub fn translate_uz_{}(text: &str) -> Option<&'static str> {{\n    Some(match text {{", key.to_lowercase());
        for line in std::fs::read_to_string(&file).unwrap_or_default().lines().filter(|l| !l.starts_with('#')) {
            if let Some((k, v)) = line.split_once('\t') {
                let _ = writeln!(o, "        {:?} => {:?},", unescape(k), unescape(v));
            }
        }
        let _ = writeln!(o, "        _ => return None,\n    }})\n}}");
    }
    o
}

/// Our Russian rows from the `catalog-ru.tsv` that `cargo xt i18n export` wrote next to `overlay.env`, as a `match` function.
/// The export holds upstream's Russian rows too; those are left out (`Language::tr` asks upstream's table first, so they would
/// be dead arms), judged by whether `src/i18n/ru.rs` already spells the key.
fn russian(dir: Option<&Path>) -> String {
    let mut o = String::from("pub fn translate_ru_extra(text: &str) -> Option<&'static str> {\n    Some(match text {\n");
    if let Some(file) = dir.map(|d| d.join("catalog-ru.tsv")).filter(|f| f.is_file()) {
        println!("cargo::rerun-if-changed={}", file.display());
        let upstream = std::fs::read_to_string("src/i18n/ru.rs").unwrap_or_default();
        for line in std::fs::read_to_string(&file).unwrap_or_default().lines().filter(|l| !l.starts_with('#')) {
            if let Some((k, v)) = line.split_once('\t').map(|(k, v)| (unescape(k), unescape(v))) {
                if !upstream.contains(&format!("{k:?}")) {
                    let _ = writeln!(o, "        {k:?} => {v:?},");
                }
            }
        }
    }
    o + "        _ => return None,\n    })\n}\n"
}

/// The catalog escapes `\n`, `\t` and `\\`.
fn unescape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some(other) => out.push(other),
            None => out.push('\\'),
        }
    }
    out
}

fn generate_upstream() -> String {
    let mut o = String::from("// GENERATED by build_office.rs (no overlay: upstream values). Do not edit.\n");
    let _ = writeln!(o, "pub const ACTIVE: bool = false;");
    let _ = writeln!(o, "pub const PRODUCT_NAME: &str = {UPSTREAM_NAME:?};");
    let _ = writeln!(o, "pub const APP_NAME: &str = {UPSTREAM_NAME:?};");
    let _ = writeln!(o, "pub const APP_NAMES: &[(&str, &str)] = &[];");
    let _ = writeln!(o, "pub const UPSTREAM_NAMES: &[&str] = &[];");
    let _ = writeln!(o, "pub const APP_ID: &str = {UPSTREAM_APP_ID:?};");
    let _ = writeln!(o, "pub const VERSION: &str = env!(\"CARGO_PKG_VERSION\");");
    let _ = writeln!(o, "pub const COPYRIGHT: &str = \"\";");
    let _ = writeln!(o, "pub const ATTRIBUTION: &[(&str, &str)] = &[];");
    for name in ["COMMUNITY", "SHARE", "ZOTERO", "UPDATE_CHECK", "UPSTREAM_LINKS", "CONTRIBUTORS_TAB"] {
        let _ = writeln!(o, "pub const {name}: bool = true;");
    }
    let _ = writeln!(o, "pub const LINK_WEBSITE: &str = \"\";");
    let _ = writeln!(o, "pub static ICON_PNG: Option<&[u8]> = None;");
    let _ = writeln!(o, "pub static FALLBACK_FONTS: &[(&str, &[u8])] = &[];");
    o + &uzbek(None) + &russian(None)
}
