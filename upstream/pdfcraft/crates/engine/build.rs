//! Month and weekday names of the overlay's Uzbek languages. `cargo xt i18n export` writes `dates-uz-latn.tsv` and
//! `dates-uz-cyrl.tsv` (`kind.index<TAB>English<TAB>name`, all 38 rows) next to the brand overlay; this script turns them into
//! `$OUT_DIR/office_dates_gen.rs` for `office_dates.rs`. Only when both files are there does the build get `cfg(office_uz)`,
//! which adds the two languages to `DATE_LANGUAGES`. Without `OFFICE_OVERLAY_DIR` nothing is added: upstream's own list.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    println!("cargo::rerun-if-env-changed=OFFICE_OVERLAY_DIR");
    println!("cargo::rustc-check-cfg=cfg(office_uz)");
    let dir = std::env::var_os("OFFICE_OVERLAY_DIR").map(PathBuf::from);
    let files = dir.as_ref().map(|d| [d.join("dates-uz-latn.tsv"), d.join("dates-uz-cyrl.tsv")]).filter(|f| f.iter().all(|p| p.is_file()));
    let mut o = String::from("// GENERATED by build.rs from $OFFICE_OVERLAY_DIR/dates-uz-*.tsv. Do not edit.\n");
    if let (Some(dir), Some(files)) = (&dir, files) {
        println!("cargo::rustc-cfg=office_uz");
        let meta_path = dir.join("catalog-meta.env");
        println!("cargo::rerun-if-changed={}", meta_path.display());
        let meta: HashMap<String, String> = std::fs::read_to_string(&meta_path)
            .unwrap_or_default()
            .lines()
            .filter_map(|l| l.split_once('='))
            .map(|(k, v)| (k.to_string(), v.trim().to_string()))
            .collect();
        let _ = writeln!(o, "pub const EXTRA: usize = 2;");
        for ((key, fallback), file) in [("LATN", "O\u{2bb}zbekcha"), ("CYRL", "Ўзбекча")].into_iter().zip(files) {
            println!("cargo::rerun-if-changed={}", file.display());
            let mut names: HashMap<String, Vec<(usize, String)>> = HashMap::new();
            for line in std::fs::read_to_string(&file).unwrap_or_default().lines().filter(|l| !l.starts_with('#')) {
                let cols: Vec<&str> = line.split('\t').collect();
                if let [row_key, _english, name] = cols[..]
                    && let Some((kind, n)) = row_key.rsplit_once('.')
                    && let Ok(n) = n.parse::<usize>()
                {
                    names.entry(kind.to_string()).or_default().push((n, name.to_string()));
                }
            }
            let list = |kind: &str, len: usize| -> String {
                let mut v = names.get(kind).cloned().unwrap_or_default();
                v.sort();
                if v.len() != len || v.iter().enumerate().any(|(i, (n, _))| *n != i + 1) {
                    println!("cargo::error={} needs {len} rows of {kind} (1..={len})", file.display());
                }
                format!("{:?}", v.into_iter().map(|(_, name)| name).collect::<Vec<_>>())
            };
            let name = meta.get(&format!("NAME_UZ_{key}")).map_or(fallback, String::as_str);
            let _ = writeln!(
                o,
                "pub const UZ_{key}: DateLanguage = DateLanguage {{\n    code: \"uz-{}\",\n    name: {name:?},\n    months: {},\n    months_with_day: None,\n    months_short: {},\n    days: {},\n    days_short: {},\n}};",
                key.to_lowercase(),
                list("date.month", 12),
                list("date.monthShort", 12),
                list("date.day", 7),
                list("date.dayShort", 7),
            );
        }
    } else {
        let _ = writeln!(o, "pub const EXTRA: usize = 0;");
    }
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("office_dates_gen.rs");
    if let Err(e) = std::fs::write(&out, o) {
        println!("cargo::error=writing {}: {e}", out.display());
    }
}
