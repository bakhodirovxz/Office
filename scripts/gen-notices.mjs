// Merges cargo-about JSON runs (one per shipped binary) into one plain-text third-party notice file. Called by scripts/gen-notices.sh.
//   node scripts/gen-notices.mjs <out.txt> <label>=<about.json> ...
// Fails (exit 1) when a linked crate has no licence text, or a licence outside the policy appears (deny.toml allow list, the two
// documented deny exceptions, MPL-2.0 for the symphonia crates only). Output is deterministic: no paths, no dates, sorted.
import { readFileSync, writeFileSync } from 'node:fs';

const ALLOW = new Set(['MIT', 'MIT-0', 'Apache-2.0', 'Apache-2.0 WITH LLVM-exception', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib',
  'Unicode-3.0', 'BSL-1.0', 'CC0-1.0']);
const EXC = { epaint_default_fonts: ['OFL-1.1', 'Ubuntu-font-1.0'], 'webpki-root-certs': ['CDLA-Permissive-2.0'] }; // = deny.toml [[licenses.exceptions]]
const [out, ...runs] = process.argv.slice(2);
const bad = [], perBin = [], groups = new Map(), all = new Map();
for (const r of runs) {
  const [label, file] = [r.slice(0, r.indexOf('=')), r.slice(r.indexOf('=') + 1)];
  const j = JSON.parse(readFileSync(file, 'utf8'));
  const have = new Set();
  for (const l of j.licenses) for (const u of l.used_by) {
    const p = u.crate, id = `${p.name} ${p.version}`;
    have.add(id); all.set(id, p);
    const ok = ALLOW.has(l.id) || (EXC[p.name] || []).includes(l.id) || (l.id === 'MPL-2.0' && p.name.startsWith('symphonia'));
    if (!ok) bad.push(`${id}: licence ${l.id} is outside the policy`);
    const text = l.text.replace(/\r\n/g, '\n').trim();
    if (!text) { bad.push(`${id}: empty licence text`); continue; }
    const key = `${l.id}\n${text}`;
    if (!groups.has(key)) groups.set(key, { id: l.id, text, crates: new Set() });
    groups.get(key).crates.add(id);
  }
  for (const c of j.crates) { const id = `${c.package.name} ${c.package.version}`; if (!have.has(id)) bad.push(`${id}: no licence text found (${label})`); }
  perBin.push(`  ${label}: ${j.crates.length} crates`);
}
if (bad.length) { console.error([...new Set(bad)].join('\n')); process.exit(1); }
const mpl = [...all.keys()].filter((k) => [...groups.values()].some((g) => g.id === 'MPL-2.0' && g.crates.has(k))).sort();
const list = [...groups.values()].sort((a, b) => a.id.localeCompare(b.id) || [...a.crates].sort()[0].localeCompare([...b.crates].sort()[0]));
const rule = '='.repeat(78);
let t = `Third-party software notices

This product links the open-source Rust crates below. Each is used under its own licence; the licence texts and copyright
notices follow, grouped by identical text. Generated by cargo-about from the dependency graph of the shipped binaries
(scripts/gen-notices.sh; ${all.size} distinct crate versions in all). Crates per shipped binary:
${perBin.join('\n')}

${rule}
Mozilla Public License 2.0 (MPL-2.0): the Symphonia crates (${mpl.length}) in the slides application, used unmodified.
Source code: https://github.com/pdeljanov/Symphonia and https://crates.io (crate names below). Licence text:
https://www.mozilla.org/MPL/2.0/ (and below).
${rule}
`;
for (const g of list) {
  t += `\nLicence: ${g.id}\nUsed by: ${[...g.crates].sort().join(', ')}\n\n${g.text}\n\n${rule}\n`;
}
writeFileSync(out, t); // LF: .gitattributes normalises text to LF, so a fresh run compares equal in any checkout
console.log(`${all.size} crates, ${list.length} licence texts -> ${out}`);
