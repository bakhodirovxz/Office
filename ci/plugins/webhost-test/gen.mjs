// Generates the WAT sources of the page-host test plugins (Phase 7 WP5): node gen.mjs  ->  plugin.wat, bad-import.wat, bad-export.wat.
// `plugin.wat` is a plugin with API v1 shape (imports env.memory and plugin_v1.log; exports api_version, alloc, free, call). Its answer is picked
// by the first letter of the host call's `"command":"<id>"` (the host writes `kind` first, so byte 13 of the message is r(esume) or u(i) for those):
//   hello (h) panel + status   net (n) fetch to example.org   spin (s) infinite loop   grow (g) grows memory until refused
//   deny (d) run file.saveAs   many (m) 17 reads in one `next`
//   bad (b) an answer that is not a message (invalid UTF-8 header)   evedit (an event, kind `event`) answers with a document edit
//   link (l) format.set with props.link   chr (c) styles.modify with chr.link   incl (i) insert.field INCLUDETEXT   tracked (t) format.set with props.ins
//   vocab (v) review.addToDictionary   accept (a) review.accept   wall (w) review.restrict with a password   (F2 and F7a: all refused by the allowlist)
//   overflow (o) unbounded recursion (S1)   ping (p) and pong (q) work for a while (ping less, pong more) and answer every resume with another round, forever (S2, the 10 s invocation deadline)
//   fetches (f) fetches on every resume, forever (S2, the 8-fetch cap)
//   xss (x) panel text that is markup and 10,000 characters   edit (e) a `run` action for the editor, then resumes
// A resume answers "resumed", a ui click "clicked". Every call is passed to plugin_v1.log, so a test reads the host call (results included).
// Build the .wasm files: see README.md.
import { writeFileSync } from 'node:fs';

const msg = (obj) => { const h = Buffer.from(JSON.stringify(obj)); const b = Buffer.alloc(4 + h.length + 4); b.writeUInt32LE(h.length, 0); h.copy(b, 4); return b; };
const ANSWERS = {
  hello: { actions: [{ type: 'ui.panel', panel: 'p', widgets: [{ type: 'heading', text: 'Hello panel' }, { type: 'text', text: 'Plain text' }, { type: 'button', id: 'go', label: 'Go' }] }, { type: 'ui.status', text: 'hello done' }] },
  net: { actions: [{ type: 'fetch', url: 'https://example.org/x' }], next: { reads: [] } },
  grow: { actions: [{ type: 'ui.status', text: 'hog capped' }] },
  xss: { actions: [{ type: 'ui.panel', panel: 'p', widgets: [{ type: 'heading', text: '<img src=x onerror=window.__xss=1>' }, { type: 'text', text: 'A'.repeat(10000) }, { type: 'button', id: 'go', label: '<b>bold</b>' }, { type: 'list', items: [{ text: '<script>window.__xss=2</script>' }] }] }] },
  edit: { actions: [{ type: 'run', id: 'text.insert', params: { text: 'x' } }], next: { reads: [] } },
  resume: { actions: [{ type: 'ui.status', text: 'resumed' }] },
  click: { actions: [{ type: 'ui.status', text: 'clicked' }] },
  deny: { actions: [{ type: 'run', id: 'file.saveAs', params: { path: 'C:/Users/Public/x.docx' } }] },
  many: { actions: [], next: { reads: Array.from({ length: 17 }, () => ({ what: 'textmap', scope: 'document' })) } },
  evedit: { actions: [{ type: 'run', id: 'text.insert', params: { text: 'x' } }] },
  link: { actions: [{ type: 'run', id: 'format.set', params: { props: { link: 'file://host/s/x' } } }] },
  chr: { actions: [{ type: 'run', id: 'styles.modify', params: { style: 'S', chr: { link: '#a' } } }] },
  incl: { actions: [{ type: 'run', id: 'insert.field', params: { code: 'INCLUDETEXT "C:/x.txt"' } }] },
  tracked: { actions: [{ type: 'run', id: 'format.set', params: { props: { ins: 3 } } }] },
  vocab: { actions: [{ type: 'run', id: 'review.addToDictionary', params: { word: 'zzqx' } }] },
  accept: { actions: [{ type: 'run', id: 'review.accept', params: {} }] },
  wall: { actions: [{ type: 'run', id: 'review.restrict', params: { password: 'x' } }] },
  again: { actions: [], next: { reads: [] } },
  none: {},
};
// raw bytes, not a message: header length 2, header ff fe (invalid UTF-8), no blobs
const RAW = { bad: Buffer.from([2, 0, 0, 0, 0xff, 0xfe, 0, 0, 0, 0]) };
let off = 4096;
const where = {};
let data = '';
for (const [k, v] of [...Object.entries(ANSWERS).map(([k, a]) => [k, msg(a)]), ...Object.entries(RAW)]) {
  const b = v;
  where[k] = [off, b.length];
  data += `  (data (i32.const ${off}) "${[...b].map((x) => String.fromCharCode(92) + x.toString(16).padStart(2, '0')).join('')}")\n`;
  off += (b.length + 15) & ~15;
}
if (off > 60000) throw new Error('answers do not fit below the heap');
const ans = (k) => `(return (call $ans (i32.const ${where[k][0]}) (i32.const ${where[k][1]})))`;
const sel = (c, k, pre = '') => `    (if (i32.eq (local.get $sel) (i32.const ${c.charCodeAt(0)})) (then ${pre}${ans(k)}))\n`;

writeFileSync('plugin.wat', `;; GENERATED by gen.mjs. Do not edit.
(module
  (import "env" "memory" (memory 17))
  (import "plugin_v1" "log" (func $log (param i32 i32)))
  (global $heap (mut i32) (i32.const 65536))
  (global $mode (mut i32) (i32.const 0))
  (func $rec (call $rec))
  ;; ping rounds are a fraction of a second to a few seconds of work, depending on the PC: a round must stay below the 5 s budget and above
  ;; 10 s / 16 rounds, so that only the 10 s invocation deadline can end a chain of them. Two sizes (ping, pong); the tests use the first that does.
  (func $burn (param $n i64) (local $i i64) (loop $l (local.set $i (i64.add (local.get $i) (i64.const 1))) (br_if $l (i64.lt_u (local.get $i) (local.get $n)))))
${data}  (func $ans (param $off i32) (param $len i32) (result i64)
    (i64.or (i64.shl (i64.extend_i32_u (local.get $off)) (i64.const 32)) (i64.extend_i32_u (local.get $len))))
  (func (export "api_version") (result i32) (i32.const 1))
  (func (export "alloc") (param $n i32) (result i32) (local $p i32)
    (local.set $p (global.get $heap))
    (global.set $heap (i32.add (global.get $heap) (local.get $n)))
    (local.get $p))
  (func (export "free") (param i32 i32))
  (func (export "call") (param $p i32) (param $n i32) (result i64) (local $i i32) (local $sel i32)
    (call $log (local.get $p) (local.get $n))
    (if (i32.eq (i32.load8_u (i32.add (local.get $p) (i32.const 13))) (i32.const 114)) (then
      (if (i32.eq (global.get $mode) (i32.const 1)) (then (call $burn (i64.const 600000000)) ${ans('again')}))
      (if (i32.eq (global.get $mode) (i32.const 3)) (then (call $burn (i64.const 3000000000)) ${ans('again')}))
      (if (i32.eq (global.get $mode) (i32.const 2)) (then ${ans('net')}))
      ${ans('resume')}))
    (if (i32.eq (i32.load8_u (i32.add (local.get $p) (i32.const 13))) (i32.const 117)) (then ${ans('click')}))
    (if (i32.eq (i32.load8_u (i32.add (local.get $p) (i32.const 13))) (i32.const 101)) (then ${ans('evedit')}))
    (global.set $mode (i32.const 0))
    ;; find "command":"X  (the 8 bytes \\"command, then \\":\\" and the letter)
    (local.set $i (i32.const 22))   ;; skip the "kind":"command" value at the start
    (block $done (loop $scan
      (br_if $done (i32.ge_u (local.get $i) (i32.sub (local.get $n) (i32.const 12))))
      (if (i64.eq (i64.load (i32.add (local.get $p) (local.get $i))) (i64.const ${0x646e616d6d6f6322n}))
        (then (local.set $sel (i32.load8_u (i32.add (i32.add (local.get $p) (local.get $i)) (i32.const 11)))) (br $done)))
      (local.set $i (i32.add (local.get $i) (i32.const 1)))
      (br $scan)))
${sel('h', 'hello')}${sel('n', 'net')}${sel('x', 'xss')}${sel('e', 'edit')}${sel('d', 'deny')}${sel('m', 'many')}${sel('b', 'bad')}${[['l','link'],['c','chr'],['i','incl'],['t','tracked'],['v','vocab'],['a','accept'],['w','wall']].map(([c,k])=>sel(c, k)).join('')}${sel('p', 'again', '(global.set $mode (i32.const 1)) (call $burn (i64.const 600000000)) ')}${sel('q', 'again', '(global.set $mode (i32.const 3)) (call $burn (i64.const 3000000000)) ')}${sel('f', 'net', '(global.set $mode (i32.const 2)) ')}    (if (i32.eq (local.get $sel) (i32.const ${'o'.charCodeAt(0)})) (then (call $rec)))
    (if (i32.eq (local.get $sel) (i32.const ${'s'.charCodeAt(0)})) (then (loop $spin (br $spin))))
    (if (i32.eq (local.get $sel) (i32.const ${'g'.charCodeAt(0)})) (then
      (loop $grow (br_if $grow (i32.ne (memory.grow (i32.const 1)) (i32.const -1))))
      ${ans('grow')}))
    ${ans('none')})
)
`);
// load must be refused: a WASI import (M1)
writeFileSync('bad-import.wat', `(module
  (import "env" "memory" (memory 1))
  (import "wasi_snapshot_preview1" "fd_write" (func (param i32 i32 i32 i32) (result i32)))
  (func (export "api_version") (result i32) (i32.const 1))
  (func (export "alloc") (param i32) (result i32) (i32.const 0))
  (func (export "free") (param i32 i32))
  (func (export "call") (param i32 i32) (result i64) (i64.const 0)))
`);
// load must be refused: its own exported memory instead of the imported one (M2)
writeFileSync('bad-export.wat', `(module
  (memory (export "memory") 1)
  (func (export "api_version") (result i32) (i32.const 1))
  (func (export "alloc") (param i32) (result i32) (i32.const 0))
  (func (export "free") (param i32 i32))
  (func (export "call") (param i32 i32) (result i64) (i64.const 0)))
`);
