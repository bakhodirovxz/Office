"""Generates Cargo.toml for the merged spike workspace from the four upstream workspaces.
Usage: python gen_workspace.py [--root REL_PREFIX]   (default prefix ../../upstream)
Merge policy: union of keys; same key => higher version, union of features, default-features=true wins.
"""
import tomllib, sys, os
PFX = sys.argv[sys.argv.index('--root')+1] if '--root' in sys.argv else 'src'
BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'upstream')
REPOS = ['wordcraft', 'gridcraft', 'deckcraft', 'pdfcraft']
def spec(v): return {'version': v} if isinstance(v, str) else dict(v)
def vkey(v): return tuple(int(x) if x.isdigit() else 0 for x in v.lstrip('=^~').split('.'))
merged = {}; notes = []
for r in REPOS:
    t = tomllib.load(open(f'{BASE}/{r}/Cargo.toml', 'rb'))['workspace']['dependencies']
    for k, v in t.items():
        v = spec(v)
        if 'path' in v:
            v['path'] = f'{PFX}/{r}/' + v['path']
        if k not in merged: merged[k] = v; continue
        o = merged[k]
        if 'path' in v or 'git' in v:
            if o != v: notes.append(f'{k}: differing git/path spec kept first ({o.get("rev")}) vs {r}')
            continue
        if vkey(v['version']) > vkey(o['version']): notes.append(f'{k}: {o["version"]} -> {v["version"]} ({r})'); o['version'] = v['version']
        elif v['version'] != o['version']: notes.append(f'{k}: kept {o["version"]}, {r} wanted {v["version"]}')
        df_o, df_v = o.get('default-features', True), v.get('default-features', True)
        if df_o != df_v: notes.append(f'{k}: default-features merged to true ({r})')
        if not (df_o or df_v): o['default-features'] = False
        else: o.pop('default-features', None)
        fs = sorted(set(o.get('features', [])) | set(v.get('features', [])))
        if fs: o['features'] = fs
def fmt(v):
    if isinstance(v, str): return '"%s"' % v
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, list): return '[' + ', '.join(fmt(x) for x in v) + ']'
    return '{ ' + ', '.join(f'{k} = {fmt(x)}' for k, x in v.items()) + ' }'
def line(k, v):
    if list(v) == ['version']: return f'{k} = "{v["version"]}"'
    return f'{k} = {fmt(v)}'
out = []
out.append('# SPIKE (Phase 0): one virtual workspace over the four upstream Craft apps. Generated by gen_workspace.py + hand edits for [patch].')
out.append('[workspace]\nresolver = "3"')
mem = []
for r in REPOS:
    mem += [f'{PFX}/{r}/crates/*', f'{PFX}/{r}/apps/*']
out.append('members = [\n' + ''.join(f'  "{m}",\n' for m in mem) + ']')
out.append('exclude = ["%s/pdfcraft/vendor", "%s/craft-libs"]' % (PFX, PFX))
out.append('''
[workspace.package]
# CONFLICT: version 0.7.0 (word/grid/deck) vs 0.8.0 (pdfcraft; its crates require `version = "0.8.0"` on path deps) -> 0.8.0
version = "0.8.0"
edition = "2024"
license = "MIT OR Apache-2.0"
# CONFLICT: 1.90 (word/grid) vs 1.95 (deck/pdf) -> 1.95
rust-version = "1.95"
# CONFLICT: repository differs per app (storytold/<app>); one value only
repository = "https://github.com/storytold/craft-apps"
''')
out.append('[workspace.dependencies]')
for k, v in merged.items(): out.append(line(k, v))
out.append('''
# UNION of the four [workspace.lints]; loosens pdfcraft (no clippy allows upstream) -- see report.
[workspace.lints.rust]
unsafe_code = "forbid"

[workspace.lints.clippy]
dbg_macro = "warn"
todo = "warn"
too_many_arguments = "allow"
type_complexity = "allow"
self_named_constructors = "allow"
large_enum_variant = "allow"
result_large_err = "allow"

# Profiles: only the root's count. word/grid/deck: codegen-units 16, debug 0; pdfcraft: codegen-units 1.
[profile.dev.package."*"]
opt-level = 2
debug = "line-tables-only"

[profile.dev]
opt-level = 1

[profile.low-disk]
inherits = "dev"
debug = "line-tables-only"
incremental = false

[profile.release]
opt-level = 3
lto = "thin"
codegen-units = 16
debug = 0
''')
out.append('@@PATCH@@')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'Cargo.toml.gen'), 'w').write('\n'.join(out))
print('\n'.join(notes))
